/**
 * Resolve frontend URLs from the process environment (CI / Tauri parent shell)
 * and materialize them into a Vite env file so `beforeDevCommand` / `beforeBuildCommand`
 * always bake the same values into the client.
 *
 * Precedence (first non-empty wins):
 *   VITE_APP_URL | APP_URL | FRONTEND_URL
 *   VITE_API_URL | API_URL | BACKEND_URL
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function pick(...keys) {
  for (const key of keys) {
    const value = String(process.env[key] ?? '').trim()
    if (value) return { key, value }
  }
  return { key: null, value: '' }
}

function show(label, value) {
  return value ? value : '(empty / unset)'
}

const app = pick('VITE_APP_URL', 'APP_URL', 'FRONTEND_URL')
const api = pick('VITE_API_URL', 'API_URL', 'BACKEND_URL')
const isCi = String(process.env.CI ?? '').toLowerCase() === 'true' || process.env.GITHUB_ACTIONS === 'true'
const isDebug = String(process.env.TAURI_ENV_DEBUG ?? '').toLowerCase() === 'true'
const modeFile = isDebug ? '.env.development' : '.env.production'

console.log('')
console.log('========== FRONTEND ENV (Tauri → Vite) ==========')
console.log(`CI                    = ${isCi}`)
console.log(`GITHUB_ACTIONS        = ${process.env.GITHUB_ACTIONS ?? '(unset)'}`)
console.log(`TAURI_ENV_DEBUG       = ${process.env.TAURI_ENV_DEBUG ?? '(unset)'}`)
console.log(`TAURI_ENV_PLATFORM    = ${process.env.TAURI_ENV_PLATFORM ?? '(unset)'}`)
console.log(`TAURI_ENV_ARCH        = ${process.env.TAURI_ENV_ARCH ?? '(unset)'}`)
console.log(`TAURI_ENV_TARGET_TRIPLE = ${process.env.TAURI_ENV_TARGET_TRIPLE ?? '(unset)'}`)
console.log('---------- candidates (raw process.env) ----------')
console.log(`VITE_APP_URL          = ${show(null, process.env.VITE_APP_URL)}`)
console.log(`APP_URL               = ${show(null, process.env.APP_URL)}`)
console.log(`FRONTEND_URL          = ${show(null, process.env.FRONTEND_URL)}`)
console.log(`VITE_API_URL          = ${show(null, process.env.VITE_API_URL)}`)
console.log(`API_URL               = ${show(null, process.env.API_URL)}`)
console.log(`BACKEND_URL           = ${show(null, process.env.BACKEND_URL)}`)
console.log('---------- resolved (used for build) -------------')
console.log(`VITE_APP_URL          = ${show(null, app.value)}  (from ${app.key ?? 'none'})`)
console.log(`VITE_API_URL          = ${show(null, api.value)}  (from ${api.key ?? 'none'})`)
console.log('==================================================')
console.log('')

if (process.env.GITHUB_ACTIONS === 'true') {
  console.log(`::notice title=Vite build URLs::APP=${app.value || '(empty)'} API=${api.value || '(empty)'}`)
}

if (!app.value && !api.value) {
  if (isCi) {
    console.error('[tauri-env] FATAL: VITE_APP_URL / VITE_API_URL (or APP_URL/API_URL fallbacks) are empty in CI')
    process.exit(1)
  }
  console.log('[tauri-env] no process env URLs set — leaving existing .env* files for Vite loadEnv')
  process.exit(0)
}

if (app.value) process.env.VITE_APP_URL = app.value
if (api.value) process.env.VITE_API_URL = api.value

const lines = [
  '# Generated by scripts/sync-frontend-env.mjs (Tauri beforeDev/beforeBuild). Do not commit.',
  app.value ? `VITE_APP_URL=${app.value}` : '',
  api.value ? `VITE_API_URL=${api.value}` : '',
  app.value ? `APP_URL=${app.value}` : '',
  api.value ? `API_URL=${api.value}` : '',
].filter(Boolean)

const outPath = path.join(root, modeFile)
fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8')
console.log(`[tauri-env] wrote ${outPath}:`)
console.log(fs.readFileSync(outPath, 'utf8'))
